"""Generate data/results.json + data/results.js: a SIMULATED pilot progress series (Months 0-6).
SYNTHETIC DATA ONLY. There is no real post-launch data; this shows how progress will be tracked.
Deterministic (fixed seed) and independent of generate_data.py, so existing data files are untouched.
Month 0 equals the case baselines; each KPI moves roughly a third of the way to its Month-18 target by
Month 6 (m/18 of the distance) with mild noise. Run: python scripts/generate_results.py"""
import json, os, random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
MONTHS = 7  # Month 0..6
rng = random.Random(20261123)

# key: (label, unit, baseline, target, decimals, noise as fraction of |baseline-target|)
KPIS = [
    ("d2p", "Median door-to-provider", "min", 55.0, 40.0, 1),
    ("lwbs", "Left without being seen (LWBS)", "%", 4.0, 2.5, 2),
    ("unins_wait_gap", "Uninsured wait gap vs commercial", "min", 16.0, 8.0, 1),
    ("medicaid_wait_gap", "Medicaid wait gap vs commercial", "min", 10.0, 5.0, 1),
    ("unins_lwbs", "Uninsured LWBS", "%", 5.8, 3.5, 2),
    ("medicaid_lwbs", "Medicaid LWBS", "%", 4.6, 3.3, 2),
]
COMMERCIAL_LWBS = 3.0  # reference group, held at its baseline so LWBS gaps are comparable


def series(base, target, dec):
    out = []
    for m in range(MONTHS):
        v = base + (target - base) * m / 18.0
        if m:
            v += rng.uniform(-0.12, 0.12) * abs(base - target)
        out.append(round(base if m == 0 else v, dec))
    return out


def main():
    os.makedirs(DATA, exist_ok=True)
    kpis = {}
    for key, label, unit, base, target, dec in KPIS:
        kpis[key] = {"label": label, "unit": unit, "baseline": base, "target": target,
                     "series": series(base, target, dec)}
    obj = {"synthetic": True, "note": "Simulated pilot results (synthetic). No real post-launch data exists.",
           "months": list(range(MONTHS)), "target_month": 18, "commercial_lwbs": COMMERCIAL_LWBS, "kpis": kpis}
    with open(os.path.join(DATA, "results.json"), "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=1)
    with open(os.path.join(DATA, "results.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/generate_results.py. SYNTHETIC DATA ONLY (simulated pilot). Do not edit by hand. */\n")
        f.write("window.Halvian = window.Halvian || {}; Halvian.data = Halvian.data || {};\n")
        f.write("Halvian.data.results = " + json.dumps(obj, indent=1) + ";\n")
    for k, v in kpis.items():
        print(k, v["series"])


if __name__ == "__main__":
    main()
